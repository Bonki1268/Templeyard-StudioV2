import { describe, expect, it } from 'vitest';
import { parseEraYear } from './era.js';

describe('紀年換算成西元年', () => {
  it.each([
    // 民前：民國元年（1912）前 N 年
    ['民前95', 1817],
    ['民前1', 1911],
    // 查證：萬壽宮、慈德廟的原始紀年依規則換算（換算正確；原始值是否可信另行查證）
    ['民前350', 1562],
    ['民前354', 1558],
    // 民國
    ['民國58', 1969],
    ['民國1', 1912],
    ['民國76年', 1987],
    ['民國69年6月1日', 1980],
    ['民國77年9月', 1988],
    ['民64年11月', 1975],
    ['民70年5月', 1981],
    // 清代年號：元年 + N − 1
    ['康熙16', 1677],
    ['雍正5', 1727],
    ['乾隆4', 1739],
    ['嘉慶9', 1804],
    ['道光10', 1830],
    ['咸豐5', 1855],
    ['同治6', 1867],
    ['光緒8', 1882],
    ['宣統2', 1910],
    // 日本年號（日據時期）
    ['明治30', 1897],
    ['大正5', 1916],
    ['昭和10', 1935],
    // 前後空白
    ['  民國58  ', 1969],
    // 只有數字、沒寫紀年：使用者決定（2026-11-02）視為民國年
    ['58', 1969],
    ['105', 2016],
    ['順治10', 1653],
  ])('「%s」換算為西元 %i 年', (raw, expected) => {
    expect(parseEraYear(raw)).toBe(expected);
  });

  it.each([
    ['', '空白'],
    ['0', '原始資料以 0 表示沒有資料'],
    ['民前0', '年數為 0'],
    ['民國0', '年數為 0'],
    ['康熙0', '年號年數為 0'],
    ['乾隆0', '年號年數為 0'],
    ['日據0', '日據年數為 0'],
    ['日據10', '只寫日據、沒有年號，無法判斷'],
    ['不詳0', '不詳'],
    ['光緒35', '超過光緒在位年數（34 年）'],
    ['咸豐12', '超過咸豐在位年數（11 年）'],
    ['大正16', '超過大正年數（15 年）'],
    ['某某5', '不認得的紀年'],
  ])('「%s」無法判斷，留空（%s）', (raw) => {
    expect(parseEraYear(raw)).toBeNull();
  });
});
