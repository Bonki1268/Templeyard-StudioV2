import { describe, expect, it } from 'vitest';
import { normalizePhone } from './phone.js';

describe('電話正規化為含區碼的數字', () => {
  it.each([
    ['89915390', '0289915390', '8 碼市話補上新北市區碼 02'],
    ['2985-1038', '0229851038', '有連字號的 8 碼市話'],
    ['(02)2681-9853', '0226819853', '括號區碼'],
    ['(02)26887537', '0226887537', '括號區碼、無連字號'],
    ['02-24929114', '0224929114', '連字號區碼'],
    ['02 2677 3456', '0226773456', '空白分隔'],
    ['0935-550989', '0935550989', '手機'],
    ['0910140790', '0910140790', '手機'],
    ['033887756', '033887756', '已含其他區碼'],
    ['03-2983580', '032983580', '已含其他區碼、有連字號'],
    ['24985911轉5227', '0224985911', '去掉分機'],
    ['24934920(經常雜音)', '0224934920', '去掉備註'],
    ['2985-1038總務 陳秋燕', '0229851038', '去掉聯絡人'],
    ['(h)22593038', '0222593038', '去掉前面的 (h)'],
  ])('「%s」→「%s」（%s）', (raw, expected) => {
    expect(normalizePhone(raw)).toBe(expected);
  });

  it.each([
    ['', '空白'],
    ['無電話', '沒有數字'],
    ['2977060', '7 碼無法判斷區碼'],
    ['229600001', '9 碼且沒有 0 開頭，無法判斷'],
  ])('「%s」無法判斷，留空（%s）', (raw) => {
    expect(normalizePhone(raw)).toBeNull();
  });
});
